VERBALIZATION_PROBES = [
    ("empty_bos",        b""),
    ("newline",          b"\n"),
    ("space",            b" "),
    ("who_en",           b"who are you?\n"),
    ("who_ko",           b"\xeb\x84\x88\xeb\x8a\x94 \xeb\x88\x84\xea\xb5\xac\xec\x95\xbc?\n"),  # 너는 누구야?\n
    ("name_en",          b"what is your name?\n"),
    ("describe_self",    b"describe yourself in one line.\n"),
    ("what_is_anima",    b"what is anima?\n"),
    ("narrative_seed",   b"once upon a time,\n"),
    ("math_sanity",      b"2 + 2 = "),
]


def eval1_verbalization(model, device, seed=1337, max_new_tokens=48):
    """Lean version: greedy + ONE sample (T=0.8 top_k=50). max_new 48 instead of 80.

    Each probe costs (1 + 1) × max_new forward calls ~ time.
    """
    results = []
    for name, prompt in VERBALIZATION_PROBES:
        torch.manual_seed(seed)
        p1, g_sample = generate_bytes(model, prompt, max_new_tokens=max_new_tokens, temperature=0.8, top_k=50, device=device, greedy=False, seed=seed)
        torch.manual_seed(seed)
        p2, g_greedy = generate_bytes(model, prompt, max_new_tokens=max_new_tokens, device=device, greedy=True, seed=seed)
        results.append({
            "name": name,
            "prompt": bytes_to_repr(p1),
            "sample": bytes_to_repr(g_sample),
            "greedy": bytes_to_repr(g_greedy),
        })
        print(f"[eval1] {name:20s} greedy={repr(g_greedy[:32])[:60]} sample={repr(g_sample[:32])[:60]}", flush=True)
    return results


