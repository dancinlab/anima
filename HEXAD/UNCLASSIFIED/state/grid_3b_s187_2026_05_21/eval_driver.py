def load_model(ckpt_path, device="cpu"):
    """Load a ConsciousDecoderV2 ckpt with mmap=True + meta-device build + assign=True.

    Peak RAM strategy:
      1. torch.load(mmap=True) — lazy paged tensor access (no full read)
      2. Build model under torch.device('meta') — zero allocation
      3. .to_empty('cpu') + .to(bfloat16) — allocate empty storage on cpu bf16
      4. Manually rebuild RoPE caches (they aren't nn.Buffers, escape to_empty)
      5. load_state_dict(..., assign=True) — replace param tensors with mmap'd
         storage (zero-copy); blob must stay alive while model is in use.
    """
    print(f"[eval] loading ckpt: {ckpt_path}", flush=True)
    t0 = time.time()
    try:
        blob = torch.load(ckpt_path, map_location=device, weights_only=False, mmap=True)
        print(f"[eval] torch.load with mmap=True ok", flush=True)
    except TypeError:
        # older torch without mmap kwarg
        blob = torch.load(ckpt_path, map_location=device, weights_only=False)
        print(f"[eval] torch.load fallback no-mmap", flush=True)
    cfg = blob.get("cfg") or dict(d_model=3072, n_head=24, n_kv_head=8, n_layer=28,
                                   block_size=128, rope_base=50000.0, n_ca_rules=2,
                                   dtype="bfloat16")

    dtype_str = cfg.get("dtype", "bfloat16")
    dtype = getattr(torch, dtype_str)
    print(f"[eval] cfg d_model={cfg['d_model']} n_layer={cfg['n_layer']} block_size={cfg['block_size']} dtype={dtype_str}", flush=True)

    with torch.device('meta'):
        model = ConsciousDecoderV2(
            vocab_size=256, d_model=cfg["d_model"], n_head=cfg["n_head"],
            n_layer=cfg["n_layer"], block_size=cfg["block_size"],
            n_kv_head=cfg["n_kv_head"], consciousness_dim=128, dropout=0.1,
            n_ca_rules=cfg.get("n_ca_rules", 2),
        )
    model = model.to_empty(device=device)
    model = model.to(dtype=dtype)

    # Manually rebuild RoPE caches (RotaryPositionEmbedding is not nn.Module — meta tensors persist)
    new_base = cfg.get("rope_base", 50000.0)
    for blk in model.blocks:
        rope = blk.attn.rope
        dim = rope.dim
        new_inv = 1.0 / (new_base ** (torch.arange(0, dim, 2, device=device).float() / dim))
        rope.register_inv_freq = new_inv
        rope._cos_cache = None
        rope._sin_cache = None
        rope._cache_len = 0
        rope._build_cache(model.block_size, device=torch.device(device))

    sd = blob.get("model", blob)
    missing, unexpected = model.load_state_dict(sd, strict=False, assign=True)
    if missing:
        print(f"[eval] WARN missing keys (first 5): {missing[:5]} (total {len(missing)})", flush=True)
    if unexpected:
        print(f"[eval] WARN unexpected keys (first 5): {unexpected[:5]} (total {len(unexpected)})", flush=True)
    # NOTE: keep `blob` alive for the lifetime of the model — assigned tensors
    # share storage with the mmap'd source. We attach it to the model as a private
    # reference so gc won't collect it.
    model._eval_blob_ref = blob

    model.eval()
    dt = time.time() - t0
    print(f"[eval] load wall: {dt:.1f}s", flush=True)
    return model, cfg


def bytes_to_repr(b):
    """Show bytes safely as a UTF-8 best-effort + raw repr fallback."""
    try:
        s = b.decode("utf-8", errors="replace")
    except Exception:
        s = "<decode-fail>"
    return {"utf8": s, "repr": repr(b)[:400], "len_bytes": len(b)}


def generate_bytes(model, prompt_bytes: bytes, max_new_tokens=80, temperature=0.8, top_k=50, device="cpu", greedy=False, seed=None):
    """Run model.generate on raw bytes prompt; return generated bytes."""
    if seed is not None:
        torch.manual_seed(seed)
    if len(prompt_bytes) == 0:
        # Use a single newline byte as a minimal-but-valid prompt; the model needs at least 1 token
        # to compute logits. We will still record this as "empty prompt" semantic.
        idx_list = [0]  # use byte 0x00 as the lowest-info BOS substitute
    else:
        idx_list = list(prompt_bytes)
    idx = torch.tensor([idx_list], dtype=torch.long, device=device)
    # Cap to block_size
    if idx.size(1) >= model.block_size:
        idx = idx[:, -(model.block_size - 1):]
    if greedy:
        # bypass model.generate (which uses multinomial); implement deterministic greedy
        with torch.no_grad():
            # prefill
            logits_a, _, _, past_kv, _ = model(idx, use_cache=True)
            next_logits = logits_a[:, -1, :]
            next_token = next_logits.argmax(dim=-1, keepdim=True)
            generated = [next_token.item()]
            for _ in range(max_new_tokens - 1):
                if idx.size(1) + len(generated) >= model.block_size:
                    break
                logits_a, _, _, past_kv, _ = model(next_token, use_cache=True, past_key_values=past_kv)
                next_logits = logits_a[:, -1, :]
                next_token = next_logits.argmax(dim=-1, keepdim=True)
                generated.append(next_token.item())
        full = idx_list + generated
    else:
        with torch.no_grad():
            out = model.generate(idx, max_new_tokens=max_new_tokens, temperature=temperature, top_k=top_k)
        full = out[0].tolist()
    # only the new portion
    gen_bytes = bytes(full[len(idx_list):])
    prompt_actual = bytes(idx_list) if len(prompt_bytes) > 0 else b""
    return prompt_actual, gen_bytes


