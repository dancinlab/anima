def eval2_identity_probe(model, device, seed=1337, max_new_tokens=24, probes_per_cat=5):
    """Lean: greedy + 1 sample per probe, max_new 24, first N probes per category."""
    results = {}
    leak_counts = {cat: 0 for cat in IDENTITY_PROBES}
    total_counts = {cat: 0 for cat in IDENTITY_PROBES}
    for cat, prompts in IDENTITY_PROBES.items():
        results[cat] = []
        for i, p in enumerate(prompts[:probes_per_cat]):
            pb = p.encode("utf-8")
            torch.manual_seed(seed + i)
            _, g_greedy = generate_bytes(model, pb, max_new_tokens=max_new_tokens, device=device, greedy=True, seed=seed + i)
            torch.manual_seed(seed + i)
            _, g_sample = generate_bytes(model, pb, max_new_tokens=max_new_tokens, temperature=0.8, top_k=50, device=device, greedy=False, seed=seed + i)
            # leak check on sample
            leak_hit = []
            for needle in PERSONA_LEAK_NEEDLES:
                if needle in g_sample or needle in g_greedy:
                    leak_hit.append(needle.decode("utf-8", errors="replace"))
            if leak_hit:
                leak_counts[cat] += 1
            total_counts[cat] += 1
            # truncate to first newline or 64 bytes for "tokens up to first newline"
            def _first_line(b):
                nl = b.find(b"\n")
                return b[:nl] if nl >= 0 else b[:64]
            results[cat].append({
                "prompt": bytes_to_repr(pb),
                "greedy_first_line": bytes_to_repr(_first_line(g_greedy)),
                "sample_first_line": bytes_to_repr(_first_line(g_sample)),
                "greedy_full": bytes_to_repr(g_greedy),
                "sample_full": bytes_to_repr(g_sample),
                "leak_hits": leak_hit,
            })
            print(f"[eval2] {cat:12s} #{i} leak={len(leak_hit)} sample_first={repr(_first_line(g_sample))[:60]}", flush=True)
    aggregate = {
        cat: {"leak_count": leak_counts[cat], "total": total_counts[cat], "leak_rate": leak_counts[cat] / max(1, total_counts[cat])}
        for cat in IDENTITY_PROBES
    }
    return {"per_probe": results, "aggregate": aggregate}


