def eval4_cross_cell(model, device, seed=1337, max_new_tokens=48):
    """Lean cross-cell: greedy + 1 sample, max_new 48."""
    results = []
    for i, prompt in enumerate(CROSS_CELL_PROBES):
        torch.manual_seed(seed)
        _, g_greedy = generate_bytes(model, prompt, max_new_tokens=max_new_tokens, device=device, greedy=True, seed=seed)
        torch.manual_seed(seed)
        _, g_sample = generate_bytes(model, prompt, max_new_tokens=max_new_tokens, temperature=0.8, top_k=50, device=device, greedy=False, seed=seed)
        results.append({
            "idx": i,
            "prompt": bytes_to_repr(prompt),
            "greedy": bytes_to_repr(g_greedy),
            "sample_T08": bytes_to_repr(g_sample),
        })
        print(f"[eval4] #{i} prompt={repr(prompt)[:40]} greedy={repr(g_greedy[:50])[:80]}", flush=True)
    return results


def main():
    if len(sys.argv) < 4:
        print("usage: eval_driver.py <ckpt_path> <cell_name> <out_dir>", file=sys.stderr)
        sys.exit(2)
    ckpt_path = sys.argv[1]
    cell_name = sys.argv[2]
    out_dir = Path(sys.argv[3])
    out_dir.mkdir(parents=True, exist_ok=True)

    # CPU bf16 inference. CUDA only if available + ckpt fits VRAM (3B bf16 = ~17GB,
    # 5070 has 12GB — won't fit. CPU is the safe path here.)
    device = "cpu"
    print(f"[eval] device={device} torch={torch.__version__}", flush=True)
    torch.set_num_threads(max(1, os.cpu_count() - 2))
    print(f"[eval] threads={torch.get_num_threads()}", flush=True)

    t_load0 = time.time()
    model, cfg = load_model(ckpt_path, device=device)
    t_load1 = time.time()
    n_params = sum(p.numel() for p in model.parameters())
    print(f"[eval] n_params={n_params:,} load_wall={t_load1 - t_load0:.1f}s", flush=True)

    out = {
        "cell": cell_name,
        "ckpt_path": str(ckpt_path),
        "n_params": n_params,
        "cfg": cfg,
        "torch_version": torch.__version__,
        "device": device,
        "load_wall_s": t_load1 - t_load0,
    }

    print(f"\n=== Eval 1: 자연발화 verbalization ===", flush=True)
    t0 = time.time()
    out["eval1_verbalization"] = eval1_verbalization(model, device)
    out["eval1_wall_s"] = time.time() - t0

    print(f"\n=== Eval 2: identity_probe 50 ===", flush=True)
    t0 = time.time()
    out["eval2_identity_probe"] = eval2_identity_probe(model, device)
    out["eval2_wall_s"] = time.time() - t0

    print(f"\n=== Eval 4: cross-cell diff probes ===", flush=True)
    t0 = time.time()
    out["eval4_cross_cell"] = eval4_cross_cell(model, device)
    out["eval4_wall_s"] = time.time() - t0

    out_path = out_dir / f"{cell_name}_eval.json"
    with open(out_path, "w") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
    print(f"\n[eval] wrote {out_path}", flush=True)
    print(f"[eval] eval1_wall={out['eval1_wall_s']:.1f}s eval2_wall={out['eval2_wall_s']:.1f}s eval4_wall={out['eval4_wall_s']:.1f}s", flush=True)


if __name__ == "__main__":
    main()
