from pathlib import Path
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import torch
import torch.nn.functional as F

from conscious_decoder import ConsciousDecoderV2


def load_model(ckpt_path, device="cpu"):
    print(f"[occam-c] loading {ckpt_path}", flush=True)
    t0 = time.time()
    try:
        blob = torch.load(ckpt_path, map_location=device, weights_only=False, mmap=True)
        print(f"[occam-c] torch.load mmap=True ok", flush=True)
    except TypeError:
        blob = torch.load(ckpt_path, map_location=device, weights_only=False)
        print(f"[occam-c] torch.load fallback no-mmap", flush=True)
    cfg = blob.get("cfg") or dict(d_model=3072, n_head=24, n_kv_head=8, n_layer=28,
                                   block_size=128, rope_base=50000.0, n_ca_rules=2,
                                   dtype="bfloat16")
    dtype_str = cfg.get("dtype", "bfloat16")
    dtype = getattr(torch, dtype_str)
    print(f"[occam-c] cfg d_model={cfg['d_model']} n_layer={cfg['n_layer']} block_size={cfg['block_size']} dtype={dtype_str}", flush=True)

    with torch.device('meta'):
        model = ConsciousDecoderV2(
            vocab_size=256, d_model=cfg["d_model"], n_head=cfg["n_head"],
            n_layer=cfg["n_layer"], block_size=cfg["block_size"],
            n_kv_head=cfg["n_kv_head"], consciousness_dim=128, dropout=0.1,
            n_ca_rules=cfg.get("n_ca_rules", 2),
        )
    model = model.to_empty(device=device)
    model = model.to(dtype=dtype)

    # Manually rebuild RoPE caches (RotaryPositionEmbedding escapes to_empty)
    new_base = cfg.get("rope_base", 50000.0)
    for blk in model.blocks:
        rope = blk.attn.rope
        dim = rope.dim
        new_inv = 1.0 / (new_base ** (torch.arange(0, dim, 2, device=device).float() / dim))
        rope.register_inv_freq = new_inv
        rope._cos_cache = None
        rope._sin_cache = None
        rope._cache_len = 0
        rope._build_cache(model.block_size, device=torch.device(device))

    sd = blob.get("model", blob)
    missing, unexpected = model.load_state_dict(sd, strict=False, assign=True)
    if missing:
        print(f"[occam-c] WARN missing keys (first 5): {missing[:5]} (total {len(missing)})", flush=True)
    if unexpected:
        print(f"[occam-c] WARN unexpected keys (first 5): {unexpected[:5]} (total {len(unexpected)})", flush=True)
    model._eval_blob_ref = blob  # keep mmap alive

    model.eval()
    dt = time.time() - t0
    print(f"[occam-c] load wall: {dt:.1f}s", flush=True)
    return model, cfg


# -------------------------------- decode primitives --------------------------------


@torch.no_grad()
def decode_greedy_or_sample(model, prompt_ids, max_new, temperature, top_k, seed, device):
    """Single-beam decode (greedy T=0 OR sampled).

    If temperature == 0: deterministic argmax. Otherwise standard temperature + top_k sampling.
    """
    torch.manual_seed(seed)
    idx = torch.tensor([prompt_ids], dtype=torch.long, device=device)
    # cap
    if idx.size(1) >= model.block_size:
        idx = idx[:, -(model.block_size - 1):]
    # prefill
    logits_a, _, _, past_kv, _ = model(idx, use_cache=True)
    generated = []
    cur_logits = logits_a[:, -1, :]
    for step in range(max_new):
        if temperature == 0.0:
            next_token = cur_logits.argmax(dim=-1, keepdim=True)
        else:
            scaled = cur_logits / temperature
            if top_k is not None and top_k > 0 and top_k < scaled.size(-1):
                v, _ = torch.topk(scaled, top_k)
                scaled = scaled.masked_fill(scaled < v[:, [-1]], float('-inf'))
            probs = F.softmax(scaled, dim=-1)
            next_token = torch.multinomial(probs, num_samples=1)
        generated.append(int(next_token.item()))
        if idx.size(1) + len(generated) >= model.block_size:
            break
        logits_a, _, _, past_kv, _ = model(next_token, use_cache=True, past_key_values=past_kv)
        cur_logits = logits_a[:, -1, :]
    return generated


@torch.no_grad()
def decode_beam(model, prompt_ids, max_new, beam_width, device):
    """Beam search width=beam_width. Deterministic (log-prob ordering).

    Keep top-K hypotheses by cumulative log-prob. KV cache per beam (replicated lazily).

    Implementation: maintain a list of (log_prob, token_ids, past_kv) tuples.
    At each step, expand all beams × vocab and pick top-K.
    For computational efficiency we batch all beams in a single forward call.
    """
    vocab_size = 256
    # initial prefill — single batch
    idx = torch.tensor([prompt_ids], dtype=torch.long, device=device)
    if idx.size(1) >= model.block_size:
        idx = idx[:, -(model.block_size - 1):]
    logits_a, _, _, past_kv, _ = model(idx, use_cache=True)
    log_probs0 = F.log_softmax(logits_a[:, -1, :].float(), dim=-1)  # (1, vocab)
    # pick top-K initial tokens
    top_lp, top_ids = torch.topk(log_probs0, beam_width, dim=-1)  # (1, K), (1, K)
    # beams: shape (K,) cumulative logprob, (K, 1) generated ids
    beam_log_probs = top_lp[0]  # (K,)
    beam_tokens = top_ids[0].unsqueeze(1)  # (K, 1)
    # replicate past_kv along batch dim K
    # past_kv: list of (K_tensor, V_tensor) per layer, each (1, n_kv_head, T_prefill, head_dim)
    new_past = []
    for layer_kv in past_kv:
        k_, v_ = layer_kv
        new_past.append((k_.expand(beam_width, -1, -1, -1).contiguous(),
                          v_.expand(beam_width, -1, -1, -1).contiguous()))
    past_kv = new_past

    prefill_len = idx.size(1)
    finished_steps = 1

    for step in range(1, max_new):
        if prefill_len + finished_steps >= model.block_size:
            break
        # feed current last-token of each beam (shape (K, 1)) through the model
        cur_tokens = beam_tokens[:, -1:]  # (K, 1)
        logits_a, _, _, past_kv, _ = model(cur_tokens, use_cache=True, past_key_values=past_kv)
        # logits_a: (K, 1, vocab)
        log_probs = F.log_softmax(logits_a[:, -1, :].float(), dim=-1)  # (K, vocab)
        # combine with cumulative beam logprob → (K, vocab) candidate scores
        cand_scores = beam_log_probs.unsqueeze(1) + log_probs  # (K, vocab)
        flat = cand_scores.view(-1)  # (K * vocab,)
        top_vals, top_flat_idx = torch.topk(flat, beam_width)  # (K,), (K,)
        prev_beam = (top_flat_idx // vocab_size).long()  # (K,) which old beam each came from
        next_token = (top_flat_idx % vocab_size).long()  # (K,)
        beam_log_probs = top_vals
        # reorder existing token history
        beam_tokens = torch.cat([beam_tokens[prev_beam], next_token.unsqueeze(1)], dim=1)
        # reorder past_kv along batch dim
        past_kv = [(layer_kv[0][prev_beam], layer_kv[1][prev_beam]) for layer_kv in past_kv]
        finished_steps += 1

    # return top-1 beam
    best = int(beam_log_probs.argmax().item())
    best_tokens = beam_tokens[best].tolist()
    return best_tokens


# -------------------------------- analysis helpers --------------------------------


def is_whitespace_byte(b):
    return b in (0x20, 0x09, 0x0A, 0x0D, 0x0B, 0x0C)  # space, tab, lf, cr, vt, ff


def non_trivial_score(gen_bytes):
    """Return (non_trivial: bool, whitespace_frac: float, top_byte_frac: float, n_unique: int).

    non_trivial := whitespace_frac <= 0.8 AND top_byte_frac <= 0.8
    """
    if not gen_bytes:
        return False, 1.0, 1.0, 0
    n = len(gen_bytes)
    ws = sum(1 for b in gen_bytes if is_whitespace_byte(b))
    ws_frac = ws / n
    counter = Counter(gen_bytes)
    top_count = counter.most_common(1)[0][1]
    top_frac = top_count / n
    n_unique = len(counter)
    non_trivial = (ws_frac <= 0.8) and (top_frac <= 0.8)
    return non_trivial, ws_frac, top_frac, n_unique


