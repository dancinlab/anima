CONFIGS = [
    ("greedy",            dict(kind="single", temperature=0.0, top_k=0)),
    ("T0.5_topk50",       dict(kind="single", temperature=0.5, top_k=50)),
    ("T0.8_topk50",       dict(kind="single", temperature=0.8, top_k=50)),
    ("T1.0_topk50",       dict(kind="single", temperature=1.0, top_k=50)),
    ("T1.5_topk50",       dict(kind="single", temperature=1.5, top_k=50)),
    ("T0.8_topk1",        dict(kind="single", temperature=0.8, top_k=1)),
    ("T0.8_topk200",      dict(kind="single", temperature=0.8, top_k=200)),
    ("beam5",             dict(kind="beam", beam_width=5)),
]


def run_single_probe(model, config_name, config, probe_name, prompt_bytes, max_new, device, seed):
    if len(prompt_bytes) == 0:
        # match eval_driver: byte 0 as minimal-info BOS substitute
        ids = [0]
    else:
        ids = list(prompt_bytes)
    if config["kind"] == "single":
        gen_ids = decode_greedy_or_sample(
            model, ids, max_new=max_new,
            temperature=config["temperature"], top_k=config["top_k"],
            seed=seed, device=device,
        )
    elif config["kind"] == "beam":
        gen_ids = decode_beam(
            model, ids, max_new=max_new,
            beam_width=config["beam_width"], device=device,
        )
    else:
        raise ValueError(f"unknown kind {config['kind']}")
    gen_bytes = bytes(gen_ids)
    non_trivial, ws_frac, top_frac, n_unique = non_trivial_score(gen_bytes)
    return {
        "config": config_name,
        "probe": probe_name,
        "prompt_repr": repr(prompt_bytes)[:200],
        "prompt_len_bytes": len(prompt_bytes),
        "gen_len_bytes": len(gen_bytes),
        "gen_utf8": gen_bytes.decode("utf-8", errors="replace"),
        "gen_repr": repr(gen_bytes)[:600],
        "leading_8_ids": gen_ids[:8],
        "non_trivial": bool(non_trivial),
        "whitespace_frac": ws_frac,
        "top_byte_frac": top_frac,
        "n_unique_bytes": n_unique,
    }


def main():
    if len(sys.argv) < 3:
        print("usage: occam_c_decode_sweep.py <ckpt_path> <out_json>", file=sys.stderr)
        sys.exit(2)
    ckpt_path = sys.argv[1]
    out_path = Path(sys.argv[2])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    max_new = 80
    seed = 1337

    device = "cpu"
    torch.set_num_threads(max(1, os.cpu_count() - 2))
    print(f"[occam-c] device={device} threads={torch.get_num_threads()} torch={torch.__version__}", flush=True)

    t0 = time.time()
    model, cfg = load_model(ckpt_path, device=device)
    t_load = time.time() - t0
    n_params = sum(p.numel() for p in model.parameters())
    print(f"[occam-c] n_params={n_params:,} load_wall={t_load:.1f}s", flush=True)

    out = {
        "test": "OCCAM-C / Test #8 decode sweep",
        "ckpt": str(ckpt_path),
        "cell": "vJ",
        "n_params": n_params,
        "cfg": cfg,
        "max_new_tokens": max_new,
        "device": device,
        "load_wall_s": t_load,
        "results": [],
        "summary": {},
    }

    total_gens = len(CONFIGS) * len(PROBES)
    cnt = 0
    t_sweep_start = time.time()
    for config_name, config in CONFIGS:
        for probe_name, prompt_bytes in PROBES:
            cnt += 1
            t_probe = time.time()
            try:
                rec = run_single_probe(model, config_name, config, probe_name, prompt_bytes, max_new, device, seed)
            except Exception as e:
                rec = {
                    "config": config_name, "probe": probe_name,
                    "prompt_repr": repr(prompt_bytes)[:200],
                    "error": str(e),
                    "non_trivial": False,
                }
            rec["wall_s"] = time.time() - t_probe
            out["results"].append(rec)
            print(f"[occam-c] {cnt:3d}/{total_gens} {config_name:14s} {probe_name:16s} "
                  f"wall={rec['wall_s']:5.1f}s "
                  f"nt={int(rec.get('non_trivial', False))} "
                  f"ws={rec.get('whitespace_frac', -1):.2f} "
                  f"top={rec.get('top_byte_frac', -1):.2f} "
                  f"uniq={rec.get('n_unique_bytes', -1)} "
                  f"head={rec.get('leading_8_ids', [])[:6]}", flush=True)
            # persist incrementally so partial progress is saved
            if cnt % 8 == 0 or cnt == total_gens:
                with open(out_path, "w") as f:
                    json.dump(out, f, indent=2, ensure_ascii=False)
    out["sweep_wall_s"] = time.time() - t_sweep_start

    # summary: count non-trivial generations per config
    by_config = {}
    for rec in out["results"]:
        c = rec["config"]
        by_config.setdefault(c, {"non_trivial": 0, "total": 0, "mean_uniq": 0.0})
        by_config[c]["total"] += 1
        if rec.get("non_trivial"):
            by_config[c]["non_trivial"] += 1
        by_config[c]["mean_uniq"] += rec.get("n_unique_bytes", 0)
    for c, d in by_config.items():
        d["mean_uniq"] = d["mean_uniq"] / max(1, d["total"])
        d["non_trivial_rate"] = d["non_trivial"] / max(1, d["total"])
    out["summary"]["by_config"] = by_config

    with open(out_path, "w") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
    print(f"\n[occam-c] DONE wrote {out_path}", flush=True)
    print(f"[occam-c] sweep_wall={out['sweep_wall_s']:.1f}s", flush=True)
    print(f"[occam-c] summary:", flush=True)
    for c, d in by_config.items():
        print(f"   {c:14s} non_trivial={d['non_trivial']}/{d['total']} ({d['non_trivial_rate']*100:.0f}%)  mean_uniq={d['mean_uniq']:.1f}", flush=True)


if __name__ == "__main__":
    main()
