"""OCCAM-C / Test #8 — inference-time decode sweep on vJ ckpt.

8 decode configs × 10 probes = 80 generations.

Configs:
  1. greedy           — T=0, deterministic argmax
  2. T=0.5 top_k=50
  3. T=0.8 top_k=50   — original Eval 1 baseline
  4. T=1.0 top_k=50
  5. T=1.5 top_k=50
  6. T=0.8 top_k=1    — effectively greedy
  7. T=0.8 top_k=200
  8. beam_5           — beam search width=5

Each (config, probe) records:
  - generated bytes (max_new=80)
  - utf-8 best-effort decode
  - repr
  - non_trivial flag (> 80% whitespace OR > 80% repeat tokens?)
  - leading 8 token ids (for diversity inspection)

Usage:
    python3 occam_c_decode_sweep.py <ckpt_path> <out_json>
"""
