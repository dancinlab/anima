class _LCG:
    """Deterministic LCG (no numpy RNG dependency, bit-reproducible)."""
    def __init__(self, seed):
        self.s = seed & 0xFFFFFFFF

    def u(self):
        self.s = (1103515245 * self.s + 12345) & 0x7FFFFFFF
        return self.s / 0x7FFFFFFF


