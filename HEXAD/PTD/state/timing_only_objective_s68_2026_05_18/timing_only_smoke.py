    # over-claim a near-degenerate emit-distribution as an "escape".
    non_degenerate = (decision_var > TAU) and (maj_frac < MAJ_COLLAPSE_FRAC)

    return {
        "regime": regime,
        "n_steps": len(seq),
        "self_label_base_rate": base_rate,
        "n_emit_events_in_label": sum(labels),
        "on": {
            "n_decisions": on["n_decisions"],
            "n_emit_decisions": len(on_emit_times),
            "emit_time_variance": on_emit_var,
            "emit_decision_variance": decision_var,
            "majority_fraction": maj_frac,
            "non_degenerate": bool(non_degenerate),
            "collapsed_to_majority": bool(not non_degenerate),
        },
        "off_reduction": {
            "enabled": False,
            "note": "§24 hand-coded talker_should_emit threshold byte-equal "
                    "(connection-point, B-S68-5)",
            "n_emit_decisions": sum(off["emit_decisions"]),
        },
    }


