# modeling file at save time (decoder_v3.py + conscious_decoder.py +
# consciousness_laws.py). HF trust_remote_code resolves these as part of
# the model package.
#
# v3: HF's `get_cached_module_file` only copies FIRST-LEVEL relative imports
# from the module pointed to by auto_map. We therefore explicitly import
# .conscious_decoder + .consciousness_laws here so HF copies them into the
# transformers_modules cache. They are NOT used directly in this file —
