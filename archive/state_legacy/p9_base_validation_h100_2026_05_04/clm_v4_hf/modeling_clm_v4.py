"""CLMv4ForCausalLM — HF PreTrainedModel wrapper for ConsciousDecoderV3.

Generated by tool/transient_py/clm_v4_hf_format_shim.py (BG-Β 2026-05-04).

This wraps the legacy ConsciousDecoderV3 (530M, 16-layer, GQA+RoPE+SwiGLU
+PureFieldFFN+CrossAttn+CA-rules+dual-heads). For lm-eval next-token use,
forward returns CausalLMOutputWithPast(logits=logits_a) and discards
logits_g + tensions (training-only signals).

The wrapped decoder is ConsciousDecoderV3 from ready/anima/models/legacy/
decoder_v3.py. To make this `trust_remote_code=True` self-contained, the
shim copies the decoder source files alongside this modeling file at save
time — see clm_v4_hf_format_shim.py:_copy_legacy_sources().
"""

