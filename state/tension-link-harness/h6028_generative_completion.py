def make_linrec_book(a, b, c, length):
    """Linear recurrence mod 256: x[k] = (a*x[k-1] + b*x[k-2] + c) mod 256.
    Rule-bearing / compressible: fit (a,b,c) from 4 consecutive bytes, extrapolate."""
    x = [a % 256, b % 256]
    for _ in range(length - 2):
        x.append((a * x[-1] + b * x[-2] + c) % 256)
    return np.array(x[:length], dtype=np.uint8)


# ── recall engine (H_6018 Hopfield-style nearest-stored, content-addressable) ──
def nearest_stored(cue_bytes, known_mask, library):
    """Content-addressable recall: among STORED books, return the one closest to the
    cue on the SURVIVING (known) bytes. This is the H_6018/H_6019 recall primitive:
    it can only return something already in the library, matched on what survives."""
