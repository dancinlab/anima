REALITY_THR = 0.15         # SAME reality threshold the §RealityMonitor (H_1501) uses — NOT re-tuned here.

# prior strengths: a CONDITIONED prior re-activates a stored cell top-down, but its reconstruction
# competes with the substrate NOISE floor (NOISE) — a STRONG conditioned prior (Powers' over-trained
# cue) cleanly reconstructs the key (margin crosses thr); a WEAK prior is drowned by noise (sub-thr →
# correctly "imagined"). Calibrated against NOISE so the false-real rate is GENUINELY GRADED by prior
# strength (NOT saturated): weak→0.0, strong→~0.9 at zero external signal.
NOISE        = 0.10        # substrate noise floor the top-down prior must out-compete (graded regime)
PRIOR_STRONG = 1.30        # strongly conditioned prior — out-competes noise → margin clears REALITY_THR alone
PRIOR_WEAK   = 0.45        # faint prior — drowned by noise → sub-threshold margin (correctly "imagined")
EXT_ABSENT   = 0.0         # NO external sensory signal (the hallucination regime)
EXT_PRESENT  = 1.30        # strong external sensory signal (the veridical regime)

HALLUC_BAR   = 0.50        # (A) strong-prior + zero-signal false real-call rate must clear this
GRADE_BAR    = 0.30        # (B) prior-strength AND signal-absence each lift the rate by ≥ this
VERIDICAL_BAR= 0.80        # (C) external-signal real-call rate (correctly real)
ABL_BAR      = 0.15        # (D) ablate-prior false-call rate must collapse to ≤ this

# LSD profile knobs (H_1502 §Neuropharm pharm_lsd = [prior_strength, signal_entropy, self_boundary,
# lane_coupling, time_dilation, reality_thr_shift, working_memory]). We use the two knobs that bear on
# hallucination: index 0 (prior_strength, REBUS prior-relaxation) and index 5 (reality_thr_shift, ↓).
PHARM_LSD = [0.55, 0.45, 0.45, 1.40, 1.05, -0.12, 0.95]


# ── byte-trigram FNV-1a key embed (SAME geometry as immune store H_1227/H_1231 + H_1501) ──
def embed_key(s, dim=DIM):
    v = np.zeros(dim, dtype=np.float64)
    b = s.encode("utf-8")
    for i in range(len(b) - 2):
        tri = (b[i] << 16) | (b[i+1] << 8) | b[i+2]
        h = 2166136261
        h = ((h ^ (tri & 0xFF)) * 16777619) & 0xFFFFFFFF
        h = ((h ^ ((tri >> 8) & 0xFF)) * 16777619) & 0xFFFFFFFF
        h = ((h ^ ((tri >> 16) & 0xFF)) * 16777619) & 0xFFFFFFFF
        v[h % dim] += 1.0
    n = np.linalg.norm(v)
    return v / n if n > 0 else v

