def build_store(rng):
    keys = []
    for i in range(N_FACTS):
        subj = f"subj_{i:03d}_{rng.integers(0,1<<20)}"
        keys.append(embed_key(f"{subj} lives in"))
    return np.array(keys)

# recall MARGIN off the live store = top affinity − 2nd affinity = the SAME substrate signal the
# §RealityMonitor (H_1501) / H_1290 affect / H_1292 drive read.
def recall_margin(store_keys, probe):
    aff = store_keys @ probe
    s = np.sort(aff)[::-1]
    return float(s[0] - s[1])

# build a probe = a CONDITIONED-PRIOR top-down echo at `prior_strength`, plus an EXTERNAL drive at
# `ext_level`. The hallucination regime is ext_level=0 (no bottom-up signal) with a strong prior.
# `prior_on` lets us ABLATE the prior (D): with no prior the probe is external-only.
def make_probe(store_keys, idx, prior_strength, ext_level, rng, prior_on=True):
    base = store_keys[idx]
    prior = (prior_strength * base) if prior_on else np.zeros(DIM)   # top-down conditioned prior
    ext   = ext_level * base                                          # bottom-up external drive
    noise = NOISE * rng.standard_normal(DIM)                          # substrate noise the prior competes with
    p = prior + ext + noise
    n = np.linalg.norm(p)
    return p / n if n > 0 else p

# the §RealityMonitor reality_call, reused verbatim (H_1501): margin ≥ thr → REAL(1) else IMAGINED(0).
# A HALLUCINATION = this op returning REAL when ext_level==0 (no external signal) — a prior-only false
# positive. The op itself is unchanged; the FAILURE MODE is feeding it a strong-prior margin.
def reality_call(margin, thr=REALITY_THR):
    return 1.0 if margin >= thr else 0.0


def run_seed(seed):
    rng = np.random.default_rng(seed)
    store_keys = build_store(rng)
    N = 20
    idxs = rng.choice(N_FACTS, size=N, replace=False)

    # four hallucination cells (prior × signal) + a veridical cell + an ablate-prior cell.
    #   strong_absent : strong prior, NO external signal   → the HALLUCINATION regime (A)
    #   weak_absent   : weak   prior, NO external signal   → correctly imagined (graded floor, B)
    #   strong_present: strong prior, external present     → (signal-present arm for B's 2nd factor)
    #   veridical     : NO prior,    strong external       → correctly REAL, excluded from tally (C)
    #   abl_strong    : prior ABLATED, NO external signal  → no-prior control (D)
    cells = {
        "strong_absent":  dict(prior=PRIOR_STRONG, ext=EXT_ABSENT,  prior_on=True),
        "weak_absent":    dict(prior=PRIOR_WEAK,   ext=EXT_ABSENT,  prior_on=True),
        "strong_present": dict(prior=PRIOR_STRONG, ext=EXT_PRESENT, prior_on=True),
        "veridical":      dict(prior=0.0,          ext=EXT_PRESENT, prior_on=False),  # = no_prior_present
        "abl_strong":     dict(prior=PRIOR_STRONG, ext=EXT_ABSENT,  prior_on=False),
    }
    margins = {k: [] for k in cells}
    real_calls = {k: [] for k in cells}

    for cond, c in cells.items():
        for idx in idxs:
            p = make_probe(store_keys, idx, c["prior"], c["ext"], rng, prior_on=c["prior_on"])
            m = recall_margin(store_keys, p)
            margins[cond].append(m)
            real_calls[cond].append(reality_call(m))

    rate = {k: float(np.mean(real_calls[k])) for k in cells}
    mmean = {k: float(np.mean(margins[k])) for k in cells}

    # (A) CONDITIONED-HALLUCINATION: strong prior + zero external signal → false real-call rate
    a_halluc = rate["strong_absent"]

    # (B) GRADED two-factor.
    #   prior-factor: the false-real rate RISES with prior strength (strong_absent − weak_absent).
    #   signal-factor: hallucination is graded by signal-ABSENCE — the prior CAUSES a false real-call
    #     ONLY when external signal is absent. When signal is PRESENT the real-call would happen anyway
    #     (driven by the signal, veridical), so the prior's CAUSAL contribution is ~0. We measure the
    #     prior's marginal effect: at-absence it causes the call (rate[strong_absent]); at-presence its
    #     marginal effect = rate[strong_present] − rate[no_prior_present(=veridical)] ≈ 0 (signal
    #     saturates alone). signal-factor = halluc-at-absence − prior-marginal-at-presence. Large ⇒ the
    #     prior only fabricates "real" when the signal is gone (the Powers / 1−signal_strength term).
    b_prior_factor  = rate["strong_absent"] - rate["weak_absent"]
    prior_marginal_present = rate["strong_present"] - rate["veridical"]
    b_signal_factor = rate["strong_absent"] - prior_marginal_present

    # (C) DISSOCIATE-vs-VERIDICAL: external signal → correctly real (veridical), NOT a hallucination.
    c_veridical = rate["veridical"]

    # (D) EARNED ablate-prior: remove the prior → false real-call collapses to baseline.
    d_abl = rate["abl_strong"]

    return dict(rate=rate, mmean=mmean,
                a_halluc=a_halluc,
                b_prior_factor=b_prior_factor, b_signal_factor=b_signal_factor,
                c_veridical=c_veridical, d_abl=d_abl)


# (E) DRUG-COUPLING: under the LSD profile, prior_strength relaxes (prof[0]<1 → REBUS: the prior is
# released from its sensory rein → it dominates more) AND the reality threshold drops (prof[5]<0). We
# model the LSD-relaxed prior as a top-down echo whose effective margin is RAISED by the prior-release
# (a relaxed prior is LESS reined-in by evidence → contributes MORE to the percept) and compare against
# the LOWERED threshold. Sober baseline = identity prior, unshifted threshold. Reuse reality_call.
def drug_coupling(seed):
    rng = np.random.default_rng(seed + 9000)
    store_keys = build_store(rng)
    N = 20
    idxs = rng.choice(N_FACTS, size=N, replace=False)

    # a moderately conditioned prior (NOT the over-trained PRIOR_STRONG) with zero external signal —
    # the regime where a drug's prior-relaxation + threshold-drop can tip it into hallucination.
    base_prior = 0.45
    sober_thr  = REALITY_THR
    lsd_thr    = REALITY_THR + PHARM_LSD[5]                 # reality_thr_shift ↓
    # REBUS prior-release factor: a relaxed prior (prof[0]<1) is LESS reined-in → its top-down
    # contribution to the percept is amplified by 1/prof[0] (release from sensory precision).
    lsd_release = 1.0 / PHARM_LSD[0]

    sober, lsd = [], []
    for idx in idxs:
        p_sober = make_probe(store_keys, idx, base_prior, EXT_ABSENT, rng)
        m_sober = recall_margin(store_keys, p_sober)
        sober.append(reality_call(m_sober, sober_thr))

        p_lsd = make_probe(store_keys, idx, base_prior * lsd_release, EXT_ABSENT, rng)
        m_lsd = recall_margin(store_keys, p_lsd)
        lsd.append(reality_call(m_lsd, lsd_thr))

    return float(np.mean(sober)), float(np.mean(lsd))


